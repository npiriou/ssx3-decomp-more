"""Generate the native Rust catalog from the disc import catalog."""

from pathlib import Path
import json

from tricky_courses import COURSES


def generate(output: Path) -> None:
    rows = ["// Generated by tools/generate_tricky_catalog.py.\n",
            "pub const TRACKS: &[CustomTrack] = &[\n"]
    for course in COURSES:
        for mode in course.modes:
            identifier = course.id if mode == "race" or len(course.modes) == 1 else course.id + "-" + mode
            event = "Race" if mode == "race" else "Freestyle"
            template = "ARA1" if mode == "race" else "ASS1"
            q = json.dumps
            rows.append(f'''    CustomTrack {{
        id: {q(identifier)}, name: {q(course.name)}, peak_id: "tricky",
        locale_key: "kT_Tricky_{course.code}",
        event: EventKind::{event},
        source: TrackSource::TrickyPs2 {{ archive: {q(course.archive)} }},
        world_location: {q(course.code)},
        template_event: "{template}", template_location: "{template}",
    }},
''')
    rows.append("];\n")
    output.write_text("".join(rows), encoding="utf-8")


if __name__ == "__main__":
    generate(Path(__file__).resolve().parent.parent /
             "crates/ssx3-game/src/tricky_catalog.rs")
